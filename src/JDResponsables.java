    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
            Responsable res = new Responsable (  
            TFCurpr.getText(),
            TFNombrer.getText(),
            CBSexor.getSelectedItem().toString(),
            TFTelefono.getText(),
            TFParentesco.getText(),
            CBEstador.getSelectedItem().toString()
        );
        
        if (res.insertar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "DATOS DEL RESPONSABLE REGISTRADOS CORRECTAMENTE.");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "ERROR AL REGISTRAR LOS DATOS DEL REPONSABLE.");
            this.dispose();
        }
        
    }//GEN-LAST:event_BRegistrarActionPerformed

