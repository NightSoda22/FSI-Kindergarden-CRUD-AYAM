    private void BBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BBorrarActionPerformed
        Bitacora bitacora = new Bitacora (
            LFolio.getText(),    
            LFecha.getText(),
            CBTipo.getSelectedItem().toString(),
            TAObservaciones.getText(),
            CBInfante.getSelectedItem().toString(),
            CBResponsable.getSelectedItem().toString(),
            CBEducador.getSelectedItem().toString()
        );  
            
       
        
        if (bitacora.borrar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "REGISTRO ELIMINADO DE BITÁCORA");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "ERORR AL ELIMINAR EL REGISTRO DE LA BITÁCORA");
            this.dispose();
        }
    }//GEN-LAST:event_BBorrarActionPerformed

    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
        Bitacora bitacora = new Bitacora (
            LFolio.getText(),    
            LFecha.getText(),
            CBTipo.getSelectedItem().toString(),
            TAObservaciones.getText(),
            CBInfante.getSelectedItem().toString(),
            CBResponsable.getSelectedItem().toString(),
            CBEducador.getSelectedItem().toString()
        );  
            
       
        
        if (bitacora.insertar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "REGISTRO COMPLETADO CON EXITO.");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "ERROR, NO FUE POSIBLE HACER EL REGISTRO.");
            this.dispose();
        }
        
    }//GEN-LAST:event_BRegistrarActionPerformed

